"""Pydantic schemas for consultation and health endpoints."""

from datetime import datetime, timezone
from typing import Any, List, Optional
from pydantic import BaseModel, Field

from app.schemas import (
    CLINICAL_SAFETY_DISCLAIMER,
    MissingInformation,
    ReferencePassage,
    SafetyReviewFlag,
)


class HealthResponse(BaseModel):
    """Health check response schema."""
    status: str = Field(default="healthy", description="Status of the backend service")
    service: str = Field(default="meditrace-backend", description="Service identifier")
    version: str = Field(default="0.1.0", description="API version")
    mock_engine_active: bool = Field(
        default=True,
        description="Indicates whether mock AI engine is active"
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Timestamp of the health check"
    )


class SafetyAlert(BaseModel):
    """Safety alert / clinical flag schema."""
    alert_id: str = Field(..., description="Unique alert identifier")
    severity: str = Field(
        ...,
        description="Severity level: HIGH, MEDIUM, LOW, or INFO"
    )
    category: str = Field(
        default="Medication Safety",
        description="Alert category (e.g., Allergy, Interaction, Contraindication)"
    )
    title: str = Field(..., description="Short summary of the alert")
    description: str = Field(..., description="Detailed description of the flagged issue")
    recommendation: str = Field(..., description="Recommended clinician action")


class SOAPNote(BaseModel):
    """SOAP clinical note structure."""
    subjective: str = Field(..., description="Patient symptoms, history, and narrative")
    objective: str = Field(..., description="Observations, vital signs, physical exam")
    assessment: str = Field(..., description="Clinical diagnoses and differentials")
    plan: str = Field(..., description="Treatment plan, prescriptions, and follow-up")
    note_id: Optional[str] = Field(default=None, description="Unique note identifier")
    status: Optional[str] = Field(default="draft_pending_review", description="Lifecycle status")
    disclaimer: Optional[str] = Field(default=CLINICAL_SAFETY_DISCLAIMER, description="Clinical safety disclaimer")
    safety_flags: List[SafetyReviewFlag] = Field(default_factory=list, description="Safety review flags linked to note")
    missing_information: List[MissingInformation] = Field(default_factory=list, description="Missing clinical data records")
    references: List[ReferencePassage] = Field(default_factory=list, description="Retrieved guideline reference passages")


class ConsultationRequest(BaseModel):
    """Request payload for processing an ambient clinical consultation."""
    patient_id: str = Field(..., min_length=1, description="Patient medical record identifier")
    patient_name: Optional[str] = Field(default=None, description="Patient full name")
    patient_age: Optional[int] = Field(default=None, ge=0, le=130, description="Patient age")
    patient_gender: Optional[str] = Field(default=None, description="Patient gender")
    transcript: str = Field(..., min_length=10, description="Ambient doctor-patient conversation transcript")
    known_allergies: List[str] = Field(default_factory=list, description="List of patient allergies")
    current_medications: List[str] = Field(default_factory=list, description="List of current medications")
    existing_conditions: List[str] = Field(default_factory=list, description="List of chronic/existing conditions")


class ConsultationResponse(BaseModel):
    """Response payload containing generated clinical note and safety verification."""
    consultation_id: str = Field(..., description="Unique consultation identifier")
    patient_id: str = Field(..., description="Patient medical record identifier")
    encounter_id: Optional[str] = Field(default=None, description="Clinical encounter identifier")
    # Prominently labeled mock fields
    is_mock: bool = Field(
        default=True,
        description="Explicit flag confirming this is a mock response until Member A AI engine is connected"
    )
    engine_source: str = Field(
        default="MOCK_CLINICAL_AI_ENGINE (Awaiting Member A Model)",
        description="Source of the clinical AI engine"
    )
    mock_disclaimer: Optional[str] = Field(
        default="[MOCK RESPONSE] Generated by integration scaffold. Member A's AI engine will replace this output.",
        description="Prominent mock disclaimer for UI and audit logs"
    )
    clinical_disclaimer: Optional[str] = Field(
        default=CLINICAL_SAFETY_DISCLAIMER,
        description="Clinical safety prototype disclaimer"
    )
    workflow_status: str = Field(
        default="completed",
        description="Workflow completion status: 'completed' or 'failed'"
    )
    retrieval_status: Optional[str] = Field(
        default=None,
        description="Status of guideline evidence retrieval ('success', 'no_evidence_found', 'unavailable_error')"
    )
    draft_note: SOAPNote = Field(..., description="Generated draft clinical SOAP note")
    safety_alerts: List[SafetyAlert] = Field(
        default_factory=list,
        description="Real-time clinical safety flags"
    )
    safety_flags: List[SafetyReviewFlag] = Field(
        default_factory=list,
        description="Structured safety review flags from Member A clinical safety engine"
    )
    missing_information: List[MissingInformation] = Field(
        default_factory=list,
        description="Explicit clinical information gaps identified during encounter"
    )
    reference_passages: List[ReferencePassage] = Field(
        default_factory=list,
        description="Retrieved clinical reference passages with provenance"
    )
    suggested_icd10_codes: List[str] = Field(
        default_factory=list,
        description="Suggested ICD-10 diagnostic codes"
    )
    error: Optional[str] = Field(
        default=None,
        description="Non-sensitive error information if workflow execution failed"
    )
    error_stage: Optional[str] = Field(
        default=None,
        description="Stage in workflow where error was encountered"
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Timestamp of response creation"
    )
