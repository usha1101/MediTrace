    def _extract_symptoms_and_duration(self, transcript: str) -> dict:
        transcript_lower = transcript.lower()

        # 1. Extract symptoms
        symptoms = []
        if "sore throat" in transcript_lower or "throat" in transcript_lower:
            symptoms.append("sore throat")
        if "body ache" in transcript_lower or "body aches" in transcript_lower or "aches" in transcript_lower:
            symptoms.append("body aches")
        if "swallow" in transcript_lower or "dysphagia" in transcript_lower:
            symptoms.append("pain with swallowing (dysphagia)")
        if "fever" in transcript_lower or "feverish" in transcript_lower:
            symptoms.append("fever (patient-reported)")
        if "cough" in transcript_lower:
            symptoms.append("cough")
        if "headache" in transcript_lower:
            symptoms.append("headache")
        if "fatigue" in transcript_lower or "tired" in transcript_lower:
            symptoms.append("fatigue")
        if "chills" in transcript_lower:
            symptoms.append("chills")

        # 2. Extract duration
        duration = None
        duration_match = re.search(
            r"\b(?:for|past|last|over|since)\s+(\d+\s+(?:days?|weeks?|months?|hours?)|yesterday|today)\b",
            transcript,
            re.IGNORECASE,
        )
        if duration_match:
            duration = duration_match.group(1).strip()
        else:
            num_match = re.search(r"\b(\d+\s+(?:days?|weeks?|months?|hours?))\b", transcript, re.IGNORECASE)
            if num_match:
                duration = num_match.group(1).strip()

        return {
            "symptoms": symptoms,
            "duration": duration,
            "has_reported_fever": "fever" in transcript_lower or "feverish" in transcript_lower,
        }

    def _generate_mock_subjective(self, request: ConsultationRequest) -> str:
        name_info = f"Patient {request.patient_name or request.patient_id}"
        age_gender = ""
        if request.patient_age and request.patient_gender:
            age_gender = f" ({request.patient_age} y/o {request.patient_gender})"
        elif request.patient_age:
            age_gender = f" ({request.patient_age} y/o)"
        elif request.patient_gender:
            age_gender = f" ({request.patient_gender})"

        extracted = self._extract_symptoms_and_duration(request.transcript)
        symptoms_str = ", ".join(extracted["symptoms"]) if extracted["symptoms"] else "General encounter narrative"
        duration_str = extracted["duration"] or "Not explicitly documented in encounter"

        fever_status = ""
        if extracted["has_reported_fever"]:
            fever_status = "\n• Fever Status: Patient reports feeling febrile (patient-reported subjective symptom; NOT a measured vital sign)."

        allergies_str = ", ".join(request.known_allergies) if request.known_allergies else "None reported"
        meds_str = ", ".join(request.current_medications) if request.current_medications else "None reported"
        conditions_str = ", ".join(request.existing_conditions) if request.existing_conditions else "None reported"

        return (
            f"[MOCK DRAFT] Subjective:\n"
            f"• Patient Context: {name_info}{age_gender}\n"
            f"• Reported Symptoms: {symptoms_str}\n"
            f"• Reported Duration: {duration_str}{fever_status}\n"
            f"• Documented Allergies: {allergies_str}\n"
            f"• Current Medications: {meds_str}\n"
            f"• Pre-existing Conditions: {conditions_str}\n"
            f"• Patient History & Dialogue Excerpt: \"{request.transcript.strip()}\""
        )

    def _generate_mock_objective(self, request: ConsultationRequest) -> str:
        transcript_lower = request.transcript.lower()
        findings = []

        # 1. Measured vital signs (only include if an actual measurement was stated/documented)
        measured_vitals = []
        bp_match = re.search(r"\b(?:bp|blood pressure)(?:\s*(?:is|was|of|:))?\s*(\d{2,3}/\d{2,3})\b", transcript_lower)
        if bp_match:
            measured_vitals.append(f"Blood pressure: {bp_match.group(1)} mmHg")

        temp_match = re.search(r"\b(?:temp|temperature)(?:\s*(?:is|was|of|:))?\s*(\d{2,3}(?:\.\d)?)\s*(?:°|f|deg)?\b", transcript_lower)
        if temp_match:
            measured_vitals.append(f"Measured temperature: {temp_match.group(1)}°F")

        hr_match = re.search(r"\b(?:hr|pulse|heart rate)(?:\s*(?:is|was|of|:))?\s*(\d{2,3})\b", transcript_lower)
        if hr_match:
            measured_vitals.append(f"Heart rate: {hr_match.group(1)} bpm")

        if measured_vitals:
            findings.append("• Measured Vital Signs: " + ", ".join(measured_vitals))
        else:
            findings.append("• Measured Vital Signs: None documented in encounter transcript (vital signs measurement pending).")

        # Explicitly distinguish patient-reported fever from measured temperature
        if ("fever" in transcript_lower or "feverish" in transcript_lower) and not temp_match:
            findings.append("• Temperature Note: Fever was patient-reported only; no thermometer reading was documented in this encounter.")

        # 2. Clinician-narrated physical examination findings (only what was explicitly observed/narrated)
        exam_findings = []
        if "erythema" in transcript_lower or "exudate" in transcript_lower or "pharynx" in transcript_lower or "throat" in transcript_lower:
            pharynx_details = []
            if "erythema" in transcript_lower:
                pharynx_details.append("tonsillar erythema")
            if "exudate" in transcript_lower:
                pharynx_details.append("tonsillar exudate")
            if pharynx_details:
                exam_findings.append(f"Pharyngeal examination: Clinician narrated observation of {' and '.join(pharynx_details)}.")
            elif "throat" in transcript_lower:
                exam_findings.append("Pharyngeal examination performed by clinician.")

        if "lung" in transcript_lower or "breath" in transcript_lower or "auscultation" in transcript_lower:
            if "clear" in transcript_lower:
                exam_findings.append("Pulmonary auscultation: Clinician narrated that breath sounds were relatively clear.")
            else:
                exam_findings.append("Pulmonary examination evaluated by clinician.")

        if exam_findings:
            findings.append("• Clinician-Narrated Physical Examination: " + " ".join(exam_findings))
        else:
            findings.append("• Physical Examination: No physical examination findings narrated in this transcript.")

        # 3. Explicit statement on unrecorded findings (avoid inventing unsupported data)
        findings.append("• Undocumented Clinical Areas: Diagnostic labs, imaging, and additional physical systems were not documented in this encounter.")

        return "[MOCK DRAFT] Objective:\n" + "\n".join(findings)

