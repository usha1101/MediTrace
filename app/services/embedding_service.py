"""
MediTrace - Embedding Service for Clinical RAG Pipelines
Integrates with the official google-genai Python SDK to produce dense vector
embeddings for reference document chunks and clinical queries.

CLINICAL SAFETY NOTICE:
-----------------------
MediTrace is an educational clinical documentation prototype.
It must NOT autonomously diagnose, prescribe, or make treatment decisions.
Dense vector embeddings generated by this component are for semantic search
and guideline retrieval only. All retrieved evidence and downstream clinical
alerts require verification by a licensed clinician.

EMBEDDING MODEL SPECIFICATION:
-----------------------------
- Default Model: gemini-embedding-001 (current supported Google GenAI embedding model)
- Dimensions: 768 standard output dimensionality via Matryoshka Representation Learning
  (supports native 3072, 1536, 768, 512, 256)
- Provider: Google Gemini API via official google-genai SDK
- Configuration:
    - GEMINI_API_KEY: Authentication key (shared with LLM services).
    - GEMINI_EMBEDDING_MODEL: Optional override (defaults to gemini-embedding-001).
    - GEMINI_EMBEDDING_DIMENSION: Optional override (defaults to 768).
- Supported Task Types:
    - RETRIEVAL_DOCUMENT: Optimization for reference passage/guideline chunk indexing.
    - RETRIEVAL_QUERY: Optimization for user queries and clinical search terms.
    - SEMANTIC_SIMILARITY: Optimization for pairwise text comparison.
"""

import logging
import math
import os
import re
from typing import Any, Dict, List, Optional, Union

from google import genai
from google.genai import errors, types
from pydantic import BaseModel, ConfigDict, Field

from app.schemas import DocumentChunk

logger = logging.getLogger(__name__)

# Default embedding model and characteristics
DEFAULT_EMBEDDING_MODEL: str = "gemini-embedding-001"
DEFAULT_EMBEDDING_DIMENSION: int = 768
DEFAULT_BATCH_SIZE: int = 100



# =====================================================================
# Service Exceptions
# =====================================================================

class EmbeddingServiceError(Exception):
    """Base exception for all MediTrace embedding operations."""
    pass


class EmbeddingConfigurationError(EmbeddingServiceError, ValueError):
    """Raised when environment variables or required configurations/inputs are missing or invalid."""
    pass


class EmbeddingAPIError(EmbeddingServiceError):
    """Raised when the underlying embedding provider API fails or raises network/auth errors."""
    pass


class EmbeddingValidationError(EmbeddingServiceError, ValueError):
    """Raised when provider responses or vector values are malformed, empty, or non-finite."""
    pass


# =====================================================================
# Result Models
# =====================================================================

class ChunkEmbedding(BaseModel):
    """
    Representation of an embedded DocumentChunk, associating its passage_id
    and provenance metadata with its dense vector embedding.
    """
    model_config = ConfigDict(str_strip_whitespace=True)

    passage_id: str = Field(..., description="Unique deterministic identifier of the embedded chunk")
    embedding: List[float] = Field(..., description="Dense float embedding vector")
    chunk: DocumentChunk = Field(..., description="The original DocumentChunk instance")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Preserved provenance metadata")

    @property
    def text(self) -> str:
        """Convenience property to access chunk text."""
        return self.chunk.text


# =====================================================================
# Embedding Service Implementation
# =====================================================================

class EmbeddingService:
    """
    Service responsible for generating dense vector embeddings from text strings
    and DocumentChunk instances using the Google Gemini API.

    Features:
    - Uses google-genai official Python SDK.
    - Configurable model via parameter or GEMINI_EMBEDDING_MODEL environment variable.
    - Configurable output dimensionality via parameter or GEMINI_EMBEDDING_DIMENSION.
    - Reuses GEMINI_API_KEY without exposing or logging secrets.
    - Preserves input order in batch embedding results.
    - Strictly validates that returned vectors are non-empty, finite, and match expected dimensions.
    - Sanitizes API errors to prevent credential or consultation text leakage.
    - Seamlessly embeds DocumentChunk objects preserving passage_id and metadata.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        client: Optional[genai.Client] = None,
        batch_size: int = DEFAULT_BATCH_SIZE,
        output_dimensionality: Optional[int] = None,
    ):
        """
        Initialize the EmbeddingService.

        Args:
            api_key: Optional API key override. If not provided, reads GEMINI_API_KEY env var.
            model: Optional model override. If not provided, reads GEMINI_EMBEDDING_MODEL env var.
            client: Optional pre-configured genai.Client instance for dependency injection/mocking.
            batch_size: Maximum number of texts per API batch call (must be > 0, non-bool).
            output_dimensionality: Optional vector dimensionality override (defaults to 768 for text-embedding-001).

        Raises:
            EmbeddingConfigurationError: If API key is missing or parameters/configuration are invalid.
        """
        resolved_key = api_key or os.getenv("GEMINI_API_KEY")
        if not resolved_key or not resolved_key.strip():
            raise EmbeddingConfigurationError(
                "GEMINI_API_KEY is not set or empty. Please configure the GEMINI_API_KEY "
                "environment variable or pass an explicit api_key."
            )
        self._api_key: str = resolved_key.strip()

        # Validate model configuration: avoid treating invalid configuration as valid default
        if model is not None:
            if not isinstance(model, str) or not model.strip():
                raise EmbeddingConfigurationError(
                    "Embedding model parameter must be a non-empty string."
                )
            self.model: str = model.strip()
        else:
            env_model = os.getenv("GEMINI_EMBEDDING_MODEL")
            if env_model is not None:
                if not env_model.strip():
                    raise EmbeddingConfigurationError(
                        "GEMINI_EMBEDDING_MODEL environment variable must not be empty or whitespace only."
                    )
                self.model = env_model.strip()
            else:
                self.model = DEFAULT_EMBEDDING_MODEL

        # Validate batch_size: ensure boolean values are rejected (bool is subclass of int)
        if isinstance(batch_size, bool) or not isinstance(batch_size, int) or batch_size <= 0:
            raise EmbeddingConfigurationError(
                f"batch_size must be a positive integer greater than 0, got {batch_size!r}."
            )
        self.batch_size: int = batch_size

        # Validate output_dimensionality
        if output_dimensionality is not None:
            if (
                isinstance(output_dimensionality, bool)
                or not isinstance(output_dimensionality, int)
                or output_dimensionality <= 0
            ):
                raise EmbeddingConfigurationError(
                    f"output_dimensionality must be a positive integer greater than 0, got {output_dimensionality!r}."
                )
            self.output_dimensionality: Optional[int] = output_dimensionality
        else:
            env_dim = os.getenv("GEMINI_EMBEDDING_DIMENSION")
            if env_dim is not None:
                try:
                    dim_val = int(env_dim.strip())
                    if dim_val <= 0:
                        raise ValueError()
                    self.output_dimensionality = dim_val
                except Exception:
                    raise EmbeddingConfigurationError(
                        f"GEMINI_EMBEDDING_DIMENSION must be a positive integer, got {env_dim!r}."
                    )
            else:
                self.output_dimensionality = DEFAULT_EMBEDDING_DIMENSION

        if client is not None:
            self._client = client
        else:
            try:
                self._client = genai.Client(api_key=self._api_key)
            except Exception as e:
                # Never leak credentials in exception message
                raise EmbeddingConfigurationError(
                    f"Failed to initialize google-genai Client: {type(e).__name__}"
                ) from e


    @property
    def client(self) -> genai.Client:
        """Access the underlying google-genai Client instance."""
        return self._client

    @staticmethod
    def validate_vector(vector: Any, expected_dim: Optional[int] = None) -> List[float]:
        """
        Validate that an embedding vector is a non-empty sequence of finite floating-point numbers.

        Args:
            vector: Raw vector returned by the provider.
            expected_dim: Optional expected vector dimensionality.

        Returns:
            Validated list of float values.

        Raises:
            EmbeddingValidationError: If the vector is malformed, empty, non-numeric, or non-finite.
        """
        if not isinstance(vector, (list, tuple)):
            raise EmbeddingValidationError(
                f"Embedding vector must be a sequence of numbers, got {type(vector).__name__}."
            )
        if len(vector) == 0:
            raise EmbeddingValidationError("Embedding vector must not be empty.")

        if expected_dim is not None and len(vector) != expected_dim:
            raise EmbeddingValidationError(
                f"Embedding vector dimension mismatch: expected {expected_dim}, got {len(vector)}."
            )

        validated: List[float] = []
        for idx, val in enumerate(vector):
            if not isinstance(val, (int, float)) or isinstance(val, bool):
                raise EmbeddingValidationError(
                    f"Embedding vector contains non-numeric value at index {idx}: {type(val).__name__}."
                )
            if not math.isfinite(val):
                raise EmbeddingValidationError(
                    f"Embedding vector contains non-finite value at index {idx}: {val}."
                )
            validated.append(float(val))

        return validated

    def embed_text(
        self,
        text: str,
        task_type: Optional[str] = None,
    ) -> List[float]:
        """
        Generate an embedding vector for a single text string.

        Args:
            text: Non-empty text string to embed.
            task_type: Optional Gemini embedding task type (e.g. 'RETRIEVAL_QUERY', 'RETRIEVAL_DOCUMENT').

        Returns:
            List of finite float numbers representing the dense embedding vector.

        Raises:
            EmbeddingConfigurationError: If text is empty or whitespace only.
            EmbeddingAPIError: If the API call fails.
            EmbeddingValidationError: If returned vector is invalid.
        """
        if not text or not isinstance(text, str) or not text.strip():
            raise EmbeddingConfigurationError("Text to embed must not be empty or whitespace only.")

        results = self.embed_texts([text], task_type=task_type)
        if not results:
            raise EmbeddingValidationError("Embedding provider returned empty result for text.")
        return results[0]

    def embed_query(self, query: str) -> List[float]:
        """
        Convenience method to generate an embedding vector for a search or user query.
        Sets task_type to 'RETRIEVAL_QUERY' for optimal retrieval similarity.

        Args:
            query: User query or search term string.

        Returns:
            Embedding vector optimized for query retrieval.
        """
        return self.embed_text(query, task_type="RETRIEVAL_QUERY")

    def embed_texts(
        self,
        texts: List[str],
        task_type: Optional[str] = None,
    ) -> List[List[float]]:
        """
        Generate embedding vectors for a list of text strings in batch.
        Guarantees preservation of input order.

        Args:
            texts: Non-empty list of non-empty text strings.
            task_type: Optional Gemini embedding task type.

        Returns:
            List of embedding vectors, strictly aligned in order with `texts`.

        Raises:
            EmbeddingConfigurationError: If `texts` is empty or contains blank items.
            EmbeddingAPIError: If the API call encounters network/provider errors.
            EmbeddingValidationError: If returned embeddings are malformed or non-finite.
        """
        if not isinstance(texts, list):
            raise EmbeddingConfigurationError(f"texts must be a list of strings, got {type(texts).__name__}.")
        if len(texts) == 0:
            raise EmbeddingConfigurationError("texts list must not be empty.")

        for idx, t in enumerate(texts):
            if not isinstance(t, str) or not t.strip():
                raise EmbeddingConfigurationError(
                    f"Text at index {idx} must not be empty or whitespace only."
                )

        all_vectors: List[List[float]] = []
        total_texts = len(texts)

        # Process in batches to respect provider batch size
        for batch_start in range(0, total_texts, self.batch_size):
            batch = texts[batch_start : batch_start + self.batch_size]

            # Notice: Never log the raw clinical text or API keys
            logger.info(
                "Embedding batch of %d text(s) (indices %d-%d of %d) using model %s",
                len(batch),
                batch_start,
                batch_start + len(batch) - 1,
                total_texts,
                self.model,
            )

            batch_vectors = self._call_provider(batch, task_type=task_type)
            if len(batch_vectors) != len(batch):
                raise EmbeddingValidationError(
                    f"Embedding count mismatch: sent {len(batch)} text(s), received {len(batch_vectors)}."
                )
            all_vectors.extend(batch_vectors)

        return all_vectors

    @staticmethod
    def _classify_http_status(code: Optional[int]) -> str:
        """Map HTTP status codes to standard, descriptive error categories."""
        status_map = {
            400: "Invalid Request",
            401: "Authentication Error",
            403: "Permission Denied / Quota Exceeded",
            404: "Model Not Found",
            429: "Rate Limit Exceeded",
            500: "Internal Server Error",
            503: "Service Unavailable",
            504: "Gateway Timeout",
        }
        return status_map.get(code, "API Error")

    def _sanitize_text(self, text: str) -> str:
        """
        Sanitize error messages to eliminate sensitive credentials, tokens, or prompt dumps.
        """
        if not text:
            return ""
        # Redact any instance of the service's API key
        sanitized = text.replace(self._api_key, "[REDACTED_KEY]")
        # Redact URL query parameter keys: ?key=... or &key=...
        sanitized = re.sub(r"([?&]key=)[^&\s'\"]+", r"\1[REDACTED_KEY]", sanitized)
        # Redact bearer tokens if present
        sanitized = re.sub(r"(Bearer\s+)[A-Za-z0-9_\-\.]+", r"\1[REDACTED_TOKEN]", sanitized, flags=re.IGNORECASE)
        # Prevent large response payload dumps from leaking clinical consultation text
        if len(sanitized) > 160:
            sanitized = sanitized[:160].rstrip() + "... [truncated]"
        return sanitized

    def _call_provider(
        self,
        batch: List[str],
        task_type: Optional[str] = None,
    ) -> List[List[float]]:
        """
        Execute API call to google-genai embed_content for a single batch of texts.
        """
        config_kwargs: Dict[str, Any] = {}
        if task_type and task_type.strip():
            config_kwargs["task_type"] = task_type.strip()
        if self.output_dimensionality is not None:
            config_kwargs["output_dimensionality"] = self.output_dimensionality

        config = types.EmbedContentConfig(**config_kwargs) if config_kwargs else None

        try:
            call_kwargs: Dict[str, Any] = {
                "model": self.model,
                "contents": batch if len(batch) > 1 else batch[0],
            }
            if config is not None:
                call_kwargs["config"] = config

            response = self._client.models.embed_content(**call_kwargs)

        except errors.APIError as e:
            # Sanitized error handling: do not expose consultation text, URL query params, or secrets
            error_code = getattr(e, "code", None)
            category = self._classify_http_status(error_code)
            raw_msg = getattr(e, "message", None) or type(e).__name__
            sanitized_msg = self._sanitize_text(raw_msg)
            code_str = f" (HTTP {error_code})" if error_code is not None else ""
            logger.error("Gemini embedding API error%s [%s]", code_str, category)
            raise EmbeddingAPIError(
                f"Gemini embedding API error{code_str} [{category}]: {sanitized_msg}"
            ) from e
        except Exception as e:
            error_type = type(e).__name__
            logger.error("Unexpected error during Gemini embedding API call: %s", error_type)
            raise EmbeddingAPIError(
                f"Unexpected error communicating with embedding API: {error_type}"
            ) from e

        # Validate response structure
        if response is None:
            raise EmbeddingValidationError("Embedding provider returned None response.")

        # Extract embeddings list from response
        raw_embeddings = getattr(response, "embeddings", None)
        if raw_embeddings is None:
            # In single-item cases, some SDK responses may populate `embedding`
            single_emb = getattr(response, "embedding", None)
            if single_emb is not None:
                raw_embeddings = [single_emb]
            elif isinstance(response, dict):
                raw_embeddings = response.get("embeddings") or (
                    [response["embedding"]] if "embedding" in response else None
                )

        if raw_embeddings is None or not isinstance(raw_embeddings, (list, tuple)):
            raise EmbeddingValidationError(
                "Embedding provider response does not contain an 'embeddings' list."
            )

        if len(raw_embeddings) == 0:
            raise EmbeddingValidationError("Embedding provider returned empty embeddings list.")

        extracted_vectors: List[List[float]] = []
        for idx, item in enumerate(raw_embeddings):
            # Extract values from ContentEmbedding object or dict
            vals = getattr(item, "values", None)
            if vals is None and isinstance(item, dict):
                vals = item.get("values")
            elif vals is None and isinstance(item, (list, tuple)):
                vals = item

            if vals is None:
                raise EmbeddingValidationError(
                    f"Embedding at index {idx} is missing 'values' vector."
                )

            # Strict dimension validation: returned vector must match expected output_dimensionality
            validated_vec = self.validate_vector(vals, expected_dim=self.output_dimensionality)
            extracted_vectors.append(validated_vec)

        return extracted_vectors


    def embed_chunks(
        self,
        chunks: List[DocumentChunk],
        task_type: Optional[str] = "RETRIEVAL_DOCUMENT",
    ) -> List[ChunkEmbedding]:
        """
        Embed a list of DocumentChunk instances.
        Preserves each chunk's passage_id, metadata, and original chunk reference in the result.

        Args:
            chunks: Non-empty list of DocumentChunk instances to embed.
            task_type: Gemini task type (defaults to 'RETRIEVAL_DOCUMENT' for reference passages).

        Returns:
            List of ChunkEmbedding instances in identical order to `chunks`.

        Raises:
            EmbeddingConfigurationError: If `chunks` is empty or contains non-DocumentChunk items.
            EmbeddingAPIError: If the API call fails.
            EmbeddingValidationError: If returned embeddings are invalid.
        """
        if not isinstance(chunks, list):
            raise EmbeddingConfigurationError(
                f"chunks must be a list of DocumentChunk, got {type(chunks).__name__}."
            )
        if len(chunks) == 0:
            raise EmbeddingConfigurationError("chunks list must not be empty.")

        texts_to_embed: List[str] = []
        for idx, chunk in enumerate(chunks):
            if not isinstance(chunk, DocumentChunk):
                raise EmbeddingConfigurationError(
                    f"Item at index {idx} is not an instance of DocumentChunk, got {type(chunk).__name__}."
                )
            if not chunk.text or not chunk.text.strip():
                raise EmbeddingConfigurationError(
                    f"DocumentChunk at index {idx} has empty or blank text."
                )
            texts_to_embed.append(chunk.text)

        # Generate vectors with order preservation
        vectors = self.embed_texts(texts_to_embed, task_type=task_type)

        results: List[ChunkEmbedding] = []
        for chunk, vector in zip(chunks, vectors):
            chunk_embedding = ChunkEmbedding(
                passage_id=chunk.passage_id,
                embedding=vector,
                chunk=chunk,
                metadata={
                    **chunk.metadata,
                    "embedding_model": self.model,
                    "embedding_dim": len(vector),
                },
            )
            results.append(chunk_embedding)

        logger.info(
            "Successfully embedded %d DocumentChunk(s) with model %s",
            len(results),
            self.model,
        )

        return results
